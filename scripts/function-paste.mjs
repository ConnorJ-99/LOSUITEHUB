// Builds one file to paste into the Supabase dashboard's Edge Function editor:
// followUp.ts and index.ts joined, so there's only one thing to copy.
// Output: supabase/.paste/assistant.ts (not committed; rebuild after changes).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = 'supabase/functions/assistant'
const logic = readFileSync(`${dir}/followUp.ts`, 'utf8')
const index = readFileSync(`${dir}/index.ts`, 'utf8')
const withoutLocalImport = index.replace(/import \{[^}]*\} from '\.\/followUp\.ts'\n/, '')
if (withoutLocalImport === index) throw new Error('Could not find the followUp.ts import in index.ts')

mkdirSync('supabase/.paste', { recursive: true })
writeFileSync('supabase/.paste/assistant.ts', `// GENERATED by npm run function:paste. Paste this whole file into the Supabase Edge Function editor.\n\n${withoutLocalImport}\n\n${logic}`)
console.log('Wrote supabase/.paste/assistant.ts')
