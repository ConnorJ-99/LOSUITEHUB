// Builds one file to paste into the Supabase dashboard's Edge Function editor:
// index.ts plus every local module it imports (followUp.ts, contract.ts).
// Each module goes in its own namespace so their private helpers can't
// collide, and index.ts's imports become aliases into those namespaces.
// Usage: npm run function:paste [-- lead-intake]   (default: assistant)
// Output: supabase/.paste/<function>.ts (not committed; rebuild after changes).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const name = process.argv[2] ?? 'assistant'
const dir = `supabase/functions/${name}`
const index = readFileSync(`${dir}/index.ts`, 'utf8')
const local = /import \{([^}]*)\} from '\.\/(\w+)\.ts'\n/g
const imports = [...index.matchAll(local)].map((m) => ({ module: m[2], names: m[1].split(',').map((n) => n.replace(/^\s*type\s+/, '').trim()).filter(Boolean) }))
if (imports.length === 0) throw new Error('Could not find the local imports in index.ts')

const namespaces = imports.map(({ module }) => {
  const code = readFileSync(`${dir}/${module}.ts`, 'utf8')
  if (/^import /m.test(code)) throw new Error(`${module}.ts must not import anything`)
  return `// ---- ${module}.ts ----\nnamespace ${module} {\n${code}\n}`
})
const aliases = imports.flatMap(({ module, names }) => names.map((n) => `import ${n} = ${module}.${n}`))
const body = index.replace(local, '')
// Keep the npm imports first, then the modules, then the function itself.
const firstCode = body.search(/^(?!import |\/\/|\s*$)/m)
const out = [body.slice(0, firstCode).trimEnd(), ...namespaces, aliases.join('\n'), body.slice(firstCode)].join('\n\n')

mkdirSync('supabase/.paste', { recursive: true })
writeFileSync(`supabase/.paste/${name}.ts`, `// GENERATED by npm run function:paste. Paste this whole file into the Supabase Edge Function editor.\n\n${out}`)
console.log(`Wrote supabase/.paste/${name}.ts (index.ts + ${imports.map((i) => `${i.module}.ts`).join(', ')})`)
